import type { Metadata } from 'next';
import Link from 'next/link';
import { cancelOrderAction, payAgainAction } from '@/app/actions';
import { ActionForm, AutoRefresh, Countdown, Notice } from '@/components/forms';
import { TicketCard, TicketView } from '@/components/ticket-card';
import { api } from '@/lib/api';
import { humanize, money, UNPAID, when } from '@/lib/format';

export const metadata: Metadata = { title: 'Your order', robots: { index: false } };

interface Order {
  reference: string;
  status: string;
  paymentStatus: string;
  currency: string;
  subtotalMinor: number;
  feesMinor: number;
  taxMinor: number;
  discountMinor: number;
  totalMinor: number;
  refundedMinor: number;
  createdAt: string;
  reservationExpiresAt: string | null;
  customer: { name: string; email: string };
  event: { id: string; slug: string; name: string; startsAt: string; timezone: string; status: string; venue: string | null };
  items: { name: string; quantity: number; unitPriceMinor: number; lineTotalMinor: number }[];
  payment: { provider: string; reference: string; checkoutUrl: string | null } | null;
  tickets: { id: string; reference: string; status: string; category: string; holderName: string | null }[];
}

export default async function OrderPage({ params, searchParams }: { params: Promise<{ reference: string }>; searchParams: Promise<{ email?: string }> }) {
  const reference = decodeURIComponent((await params).reference).toUpperCase();
  // Only `email` is read from the URL (as the guest's proof of ownership). Anything a payment
  // gateway appends (status, reference, ...) is ignored: the state below comes from the platform.
  const email = (await searchParams).email?.trim().toLowerCase();
  const query = { email };
  const path = `/orders/${encodeURIComponent(reference)}`;

  let res = await api<Order>('GET', path, { query });
  if (res.ok && UNPAID.includes(res.data.status) && res.data.payment) {
    // Ask the platform to confirm with the gateway now, in case the webhook has not arrived yet.
    await api('POST', `${path}/verify`, { query });
    res = await api<Order>('GET', path, { query });
  }
  if (!res.ok) {
    return (
      <div className="mx-auto max-w-lg space-y-4">
        <h1 className="text-2xl font-bold">Order not found</h1>
        <Notice kind="error">{res.status === 404 ? 'We could not find an order with that reference and email address.' : res.error.message}</Notice>
        <p><Link href="/orders" className="link">Look up an order</Link></p>
      </div>
    );
  }
  const o = res.data;
  const pending = UNPAID.includes(o.status);
  const paid = ['PAID', 'TICKETS_ISSUED', 'PARTIALLY_REFUNDED'].includes(o.status);
  const expired = !!o.reservationExpiresAt && new Date(o.reservationExpiresAt) < new Date();

  // QR codes are generated by the platform and only for tickets that are still valid.
  const tickets: TicketView[] = await Promise.all(
    o.tickets.slice(0, 40).map(async (t) => {
      if (t.status !== 'VALID') return { ...t, qrSvg: null };
      const d = await api<{ qrSvg: string | null }>('GET', `/tickets/${t.id}`, { query: { orderReference: o.reference, email } });
      return { ...t, qrSvg: d.ok ? d.data.qrSvg : null };
    }),
  );
  const access = email ? `orderReference=${encodeURIComponent(o.reference)}&email=${encodeURIComponent(email)}` : '';

  return (
    <div className="mx-auto max-w-3xl space-y-6">
      {pending && <AutoRefresh />}
      <header>
        <p className="text-sm text-slate-500">Order {o.reference}</p>
        <h1 className="text-2xl font-bold tracking-tight">
          {o.status === 'TICKETS_ISSUED' ? 'You are going! Your tickets are ready.' : o.status === 'PAID' ? 'Payment received' : pending ? 'Waiting for your payment' : o.status === 'REFUNDED' ? 'This order was refunded'
            : o.status === 'PARTIALLY_REFUNDED' ? 'Your order (partly refunded)' : o.status === 'FAILED' ? 'Payment was not successful' : o.status === 'EXPIRED' ? 'This order expired' : 'This order was cancelled'}
        </h1>
      </header>

      {pending && (
        <div className="card space-y-4" aria-live="polite">
          <p className="text-sm text-slate-700">
            {o.status === 'PAYMENT_PROCESSING' ? 'Your payment is being confirmed. This page updates automatically.' : 'We have not received your payment yet. This page updates automatically once the payment is confirmed.'}
          </p>
          {o.reservationExpiresAt && !expired && <p className="text-sm">Your tickets are held for another <strong><Countdown until={o.reservationExpiresAt} /></strong>.</p>}
          {expired && <p className="text-sm text-amber-800">The hold on your tickets has run out. If you have already paid, please wait a moment while we confirm it.</p>}
          <div className="flex flex-wrap items-start gap-3">
            {o.payment?.checkoutUrl && !expired && <a href={o.payment.checkoutUrl} className="btn-primary">Complete payment</a>}
            {!expired && (
              <ActionForm action={payAgainAction} submit="Try payment again" variant="secondary" className="space-y-2">
                <input type="hidden" name="reference" value={o.reference} /><input type="hidden" name="email" value={email ?? ''} />
              </ActionForm>
            )}
            <ActionForm action={cancelOrderAction} submit="Cancel order" variant="secondary" className="space-y-2">
              <input type="hidden" name="reference" value={o.reference} /><input type="hidden" name="email" value={email ?? ''} />
            </ActionForm>
          </div>
        </div>
      )}
      {o.status === 'PAID' && <Notice kind="info">Your payment was received but your tickets could not be issued automatically. Our team has been alerted and will contact you; you do not need to pay again.</Notice>}
      {o.status === 'FAILED' && <Notice kind="error">The payment did not go through and you have not been charged for this order. Your tickets were released. <Link href={`/events/${o.event.slug}`} className="underline">Start a new order</Link>.</Notice>}
      {o.status === 'EXPIRED' && <Notice kind="info">The time to pay ran out and the tickets were released. <Link href={`/events/${o.event.slug}`} className="underline">Start a new order</Link>.</Notice>}
      {o.status === 'CANCELLED' && <Notice kind="info">This order was cancelled before payment. <Link href={`/events/${o.event.slug}`} className="underline">Back to the event</Link>.</Notice>}
      {o.refundedMinor > 0 && <Notice kind="info">{money(o.refundedMinor, o.currency)} has been refunded to your original payment method. Refunded tickets are no longer valid.</Notice>}

      {tickets.length > 0 && (
        <section aria-labelledby="tickets-h">
          <h2 id="tickets-h" className="mb-3 text-lg font-semibold">Tickets</h2>
          <ul className="grid gap-4 sm:grid-cols-2">
            {tickets.map((t) => (
              <li key={t.id}><TicketCard ticket={t} pdfHref={t.status === 'VALID' ? `/tickets/${t.id}/pdf?${access}` : null} /></li>
            ))}
          </ul>
          {paid && <p className="mt-3 text-sm text-slate-600">We have also emailed your tickets to {o.customer.email}. Each QR code admits one person and can be scanned once.</p>}
        </section>
      )}

      <section className="card">
        <h2 className="text-lg font-semibold">{o.event.name}</h2>
        <p className="text-sm text-slate-600">{when(o.event.startsAt, o.event.timezone)}{o.event.venue ? ` · ${o.event.venue}` : ''}</p>
        {o.event.status === 'CANCELLED' && <p className="mt-2 text-sm font-semibold text-red-700">This event has been cancelled.</p>}
        <dl className="mt-4 space-y-1.5 text-sm">
          {o.items.map((i) => (
            <div key={i.name} className="flex justify-between gap-3"><dt>{i.quantity} × {i.name}</dt><dd className="tabular-nums">{money(i.lineTotalMinor, o.currency)}</dd></div>
          ))}
          {o.discountMinor > 0 && <div className="flex justify-between gap-3 text-emerald-700"><dt>Discount</dt><dd className="tabular-nums">−{money(o.discountMinor, o.currency)}</dd></div>}
          {o.feesMinor > 0 && <div className="flex justify-between gap-3 text-slate-600"><dt>Service fee</dt><dd className="tabular-nums">{money(o.feesMinor, o.currency)}</dd></div>}
          {o.taxMinor > 0 && <div className="flex justify-between gap-3 text-slate-600"><dt>Tax</dt><dd className="tabular-nums">{money(o.taxMinor, o.currency)}</dd></div>}
          <div className="flex justify-between gap-3 border-t border-slate-200 pt-2 font-bold"><dt>Total</dt><dd className="tabular-nums">{money(o.totalMinor, o.currency)}</dd></div>
        </dl>
        <p className="mt-4 text-xs text-slate-500">Status: {humanize(o.status)} · Payment: {humanize(o.paymentStatus)} · Placed {when(o.createdAt, o.event.timezone, 'short')}</p>
      </section>

      <p className="text-sm text-slate-600">Need help with this order? <Link href={`/support?order=${o.reference}`} className="link">Contact support</Link>.</p>
    </div>
  );
}
